def b091(P):
    b = Bld(P, 5, 8.0, 3.0, 2, "#8e9298", "#efefed", rim="#7c8086")   # 본체는 3층(8.0m)까지, 4층은 아래 유리 상자
    FL = [0.0, 3.0, 5.5, 8.0, 10.5]
    # 4층: 안쪽으로 물러난 청록 유리 상자 + 경사 단(사진 1·3)
    b.add(P.buffer(-0.25), FL[3], FL[3] + 0.4, "#8e9298")
    box = P.buffer(-0.6)
    b.add(box, FL[3] + 0.4, 10.5, "#3f6f86")
    inner = P.buffer(-0.9)
    b.add(P.buffer(-0.6).difference(inner), FL[3] + 0.4, 10.5, "#2a3138")      # 유리 상자 테두리(어두운 틀)
    b.add(box, 10.5, 10.65, "#6d7178")                                          # 유리 상자 지붕
    # 북향 좁은 면 e5 (정면, 사진 왼쪽=동쪽)
    b.fr(0.0, 1.0, 0, 0.4, 3.0, 4.4, FRM)                                       # 흰 간판 띠
    b.fr(0.15, 0.78, 0.4, 0.5, 3.25, 4.2, "#233a8c")                            # 파란 'Slow, Cali' 간판
    b.fr(0.12, 0.52, 0, 0.12, 0.3, 2.9, GLD)                                    # 점포 유리문
    b.fr(0.0, 0.1, 0, 0.35, 0.3, 3.0, FRM)
    b.fr(0.55, 0.92, 0, 0.12, 0.3, 2.9, "#1f2024")                              # 오른쪽 어두운 입구
    b.fr(0.55, 0.95, 0.12, 0.3, 3.0, 3.5, "#4a4d52")                            # 통신사 간판 띠
