from shapely.geometry import Point

from landmark_dokssuri import Edge

BRK, BRK2 = "#6b4a44", "#5e403b"
WHT, WHT2, GRY, GRY2 = "#ecece9", "#dcdcd7", "#9c9c98", "#8a8a86"
GLS, GLS2, GLD, FRM = "#6a8aa6", "#7f9db6", "#2d3138", "#f1f1ee"
RED, BLUEG, TEAL = "#a8262b", "#5f86a8", "#5f96a8"


class Bld:
    """공통 골격: 1층 + 상층 벽체 + 난간 + 옥상 + 나머지 면의 작은 창. 정면은 fr() 로 얹는다."""

    def __init__(self, P, front, H, F1, NF, wall, base, rim=None, side_gl=GLS2, west0=False):
        self.west0 = west0   # True 면 fr() 비율을 서쪽 끝=0 으로 잰다(골목 북쪽에서 남쪽 건물을 올려다보는 경우)
        self.parts = []
        self.P = P
        n = len(P.exterior.coords) - 1
        self.E = {i: Edge(P, i) for i in range(n)}
        self.fe = self.E[front]
        self.H = H
        self.FL = [0.0, F1] + [F1 + (H - F1) * k / NF for k in range(1, NF + 1)]
        self.add(P, 0, F1, base)
        self.add(P, F1, H, wall)
        inner = P.buffer(-0.3)
        self.add(P.difference(inner), H, H + 0.7, rim or wall)
        self.add(inner, H, H + 0.1, "#8d8e90")
        for i in range(n):
            if i == front:
                continue
            e = self.E[i]
            if e.L < 2.5:
                continue
            for k in range(2, len(self.FL)):
                z0 = self.FL[k - 1]
                j = 1
                while j * 2.7 < e.L - 0.6:
                    self.add(e.rect(j * 2.7 - 0.45, j * 2.7 + 0.45, 0, 0.1), z0 + 0.9, z0 + 1.9, side_gl)
                    j += 1

    def add(self, g, b, t, c):
        if g is not None and not g.is_empty:
            self.parts.append((g, b, t, c))

    def fr(self, f0, f1, o0, o1, b, t, c):
        fe = self.fe
        if self.west0:
            self.add(fe.rect(fe.L * f0, fe.L * f1, o0, o1), b, t, c)
        else:
            self.add(fe.rect(fe.L * (1 - f1), fe.L * (1 - f0), o0, o1), b, t, c)

    def bay(self, f0, f1, z):
        """흰 돌출창 상자: 받침 + 유리 + 윗덮개."""
        self.fr(f0, f1, 0, 0.55, z, z + 0.22, FRM)
        self.fr(f0 + 0.015, f1 - 0.015, 0.05, 0.45, z + 0.22, z + 1.7, GLS2)
        self.fr(f0, f1, 0, 0.55, z + 1.7, z + 1.9, FRM)

    def shop(self, f0, f1, top=3.2):
        self.fr(f0, f1, 0, 0.12, 0.3, top, GLD)


def b104(P):
    b = Bld(P, 0, 3.5, 3.5, 1, WHT, WHT2)
    b.fr(0.0, 1.0, 0, 0.5, 2.4, 3.5, WHT)
    b.fr(0.05, 0.95, 0.5, 0.6, 3.5, 4.9, WHT)             # 지붕 위 큰 간판 상자
    b.fr(0.1, 0.9, 0.6, 0.66, 3.7, 4.7, RED)              # 붉은 글씨
    b.fr(0.0, 1.0, 0, 1.2, 2.4, 2.8, RED)                 # 붉은 어닝
    b.shop(0.1, 0.9, 2.3)
    return b.parts


